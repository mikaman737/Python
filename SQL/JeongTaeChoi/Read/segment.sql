FROM tn_visit_area_info tvai
LEFT JOIN tn_adv_consume_his tach
ON tvai.sgg_cd = tach.sgg_cd;

SELECT tvai.TRAVEL_ID, tvai.VISIT_AREA_ID, tvai.ROAD_NM_ADDR, tach.ROAD_NM_ADDR, tvai.SGG_CD ,tach.SGG_CD
FROM tn_visit_area_info tvai
LEFT JOIN tn_adv_consume_his tach
ON tvai.TRAVEL_ID = tach.TRAVEL_ID
AND tvai.SGG_CD = tach.SGG_CD
WHERE tach.SGG_CD = ''
;


