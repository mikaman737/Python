-- 유독 8/26일에 수원 여행을 많이 갔음
SELECT
    VISIT_START_YMD,
    SUBSTRING_INDEX(ROAD_NM_ADDR, ' ', 1) AS SIDO,
    SUBSTRING_INDEX(SUBSTRING_INDEX(ROAD_NM_ADDR, ' ', 2), ' ', -1) AS SGG,
    COUNT(*) AS visit_cnt
FROM tn_visit_area_info
WHERE ROAD_NM_ADDR IS NOT NULL AND TRIM(ROAD_NM_ADDR) <> ''
  AND SUBSTRING_INDEX(ROAD_NM_ADDR, ' ', 1) IN (
      '서울','서울특별시','부산','부산광역시','대구','대구광역시','인천','인천광역시',
      '광주','광주광역시','대전','대전광역시','울산','울산광역시','세종','세종특별자치시',
      '경기','경기도','강원','강원도','강원특별자치도','충북','충청북도','충남','충청남도',
      '전북','전라북도','전북특별자치도','전남','전라남도','경북','경상북도','경남','경상남도',
      '제주','제주도','제주특별자치도'
  )
  AND VISIT_START_YMD = '2023-08-26'  -- 특정 날짜로 좁힐 때 주석 해제
GROUP BY VISIT_START_YMD, SIDO, SGG
ORDER BY VISIT_START_YMD, visit_cnt DESC;
