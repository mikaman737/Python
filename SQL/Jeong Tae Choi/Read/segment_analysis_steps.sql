-- 가장 많이 간 날짜 파악(동점까지 다 보기)
SELECT test.TRAVEL_START_YMD, test.cnt
FROM (
    SELECT tt.TRAVEL_START_YMD, COUNT(*) AS cnt
    FROM tn_travel tt
    GROUP BY tt.TRAVEL_START_YMD
) test
WHERE test.cnt = (
    SELECT MAX(cnt) FROM (
        SELECT COUNT(*) AS cnt
        FROM tn_travel
        GROUP BY TRAVEL_START_YMD
    ) sub
);

-- 여행 시작 날짜 분포 확인
SELECT tt.TRAVEL_START_YMD, COUNT(tt.TRAVEL_START_YMD) AS cnt
FROM tn_travel tt
GROUP BY TRAVEL_START_YMD
ORDER BY cnt DESC;

